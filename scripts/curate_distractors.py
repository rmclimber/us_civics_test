def main():
    path = Path(sys.argv[1])
    bank = json.loads(path.read_text(encoding="utf-8"))
    ids = {q["id"] for q in bank["questions"]}
    if ids != set(D):
        raise SystemExit(f"distractor IDs do not match question IDs: missing={ids-set(D)}, extra={set(D)-ids}")
    for question in bank["questions"]:
        distractors = D[question["id"]]
        if len(distractors) != 3 or len(set(distractors)) != 3:
            raise SystemExit(f"invalid distractors for question {question['id']}")
        question["distractors"] = distractors
    path.write_text(json.dumps(bank, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

if __name__ == "__main__":
    main()
